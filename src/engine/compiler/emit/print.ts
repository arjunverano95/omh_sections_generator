/**
 * A small TypeScript printer for the generated modules: JSON-like values plus `raw` code
 * fragments (function calls and identifiers the generated config imports).
 */

export class Raw {
  constructor(public readonly code: string) {}
}

export function raw(code: string): Raw {
  return new Raw(code)
}

const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/

export function printString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`
}

function printKey(key: string): string {
  return IDENTIFIER_RE.test(key) ? key : printString(key)
}

/** Prints a value as TypeScript source; keys keep insertion order. */
export function printValue(value: unknown, indent = 0): string {
  const pad = '  '.repeat(indent)
  const inner = '  '.repeat(indent + 1)
  if (value instanceof Raw) return value.code
  if (value === null) return 'null'
  if (value === undefined) return 'undefined'
  if (typeof value === 'string') return printString(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const items = value.map((item) => `${inner}${printValue(item, indent + 1)},`)
    return `[\n${items.join('\n')}\n${pad}]`
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined)
    if (entries.length === 0) return '{}'
    const lines = entries.map(([k, v]) => `${inner}${printKey(k)}: ${printValue(v, indent + 1)},`)
    return `{\n${lines.join('\n')}\n${pad}}`
  }
  throw new Error(`cannot print a ${typeof value}`)
}

/** One-line form, for arguments of helper calls. */
export function printInline(value: unknown): string {
  if (value instanceof Raw) return value.code
  if (value === null) return 'null'
  if (typeof value === 'string') return printString(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (Array.isArray(value)) return `[${value.map(printInline).join(', ')}]`
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined)
    if (entries.length === 0) return '{}'
    return `{ ${entries.map(([k, v]) => `${printKey(k)}: ${printInline(v)}`).join(', ')} }`
  }
  throw new Error(`cannot print a ${typeof value}`)
}

export function header(templateName: string, what: string): string {
  return [
    `// Generated by \`pnpm sections:compile\` from templates/${templateName}: ${what}.`,
    '// Do not edit; change the template and recompile.',
    '',
  ].join('\n')
}
